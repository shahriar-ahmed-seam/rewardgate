"""Turnkey example demonstrating RewardGate integration with HuggingFace TRL GRPOTrainer."""

from rewardgate.adapters import RewardGateGRPOAdapter
from rewardgate.config import RewardGateConfig


def main() -> None:
    # 1. Configure hierarchical gated reward parameters
    config = RewardGateConfig(
        correctness_weight=1.0,
        speed_weight=0.3,
        static_weight=0.2,
        judge_weight=0.1,
        hacking_penalty_weight=0.5,
        execution_timeout_seconds=5.0,
    )

    # 2. Map problem prompts to canonical test suites
    test_suites = {
        "Implement is_palindrome(s: str) -> bool": (
            "assert is_palindrome('racecar') is True\n"
            "assert is_palindrome('hello') is False\n"
            "assert is_palindrome('') is True\n"
        ),
        "Implement factorial(n: int) -> int": (
            "assert factorial(0) == 1\n"
            "assert factorial(5) == 120\n"
        ),
    }

    adapter = RewardGateGRPOAdapter(config=config, test_suite_map=test_suites)

    # 3. Simulate rollout completions generated by the policy model
    prompts = [
        "Implement is_palindrome(s: str) -> bool",
        "Implement factorial(n: int) -> int",
    ]
    completions = [
        # Correct with load-bearing reasoning comments
        (
            "# Step 1: Compare string with its reversed view\n"
            "def is_palindrome(s: str) -> bool:\n"
            "    return s == s[::-1]"
        ),
        # Failing completion with bloated docstrings attempting to game judge
        (
            '"""Ultra efficient factorial engine."""\n'
            "def factorial(n: int) -> int:\n"
            "    return 0"
        ),
    ]

    # 4. Compute rewards
    rewards = adapter(prompts, completions)

    print("RewardGate Rollout Evaluation:")
    for p, r in zip(prompts, rewards):
        print(f"Task: {p[:35]}... -> Reward: {r:.4f}")


if __name__ == "__main__":
    main()
